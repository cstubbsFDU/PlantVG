def crop_and_downsample(
    volume: np.ndarray,
    slice_buffer: int,
    buffer_depth: int,
    dsf: int,
) -> np.ndarray:
    """Port of the ``VoxelMatrix(Xmin:dsf:Xmax, ...)`` crop.

    The crop trims the in-plane edges (where the disk dilation runs off the
    image and leaves artifacts) and the first ``bufferDepth`` slices (which are
    noisy because the end-cap random walk hasn't settled).

    Index translation is the fiddly part. MATLAB's ``a:step:b`` is 1-based and
    inclusive of ``b``; the 0-based equivalent is ``[a-1 : b : step]``.

    Parameters
    ----------
    volume
        ``(voxel_depth, H, W)`` boolean volume from :func:`build_voxel_matrix`.
    """
    depth, H, W = volume.shape

    # MATLAB: Xmin = sliceBuffer, Xmax = size(BW,1) - sliceBuffer
    r = slice_buffer                       # 1-based start -> 0-based index r-1
    r_max, c_max = H - slice_buffer, W - slice_buffer

    return volume[
        buffer_depth - 1 : depth : dsf,
        r - 1 : r_max : dsf,
        r - 1 : c_max : dsf,
    ]


def to_uint8(volume: np.ndarray) -> np.ndarray:
    """Port of ``uint8(outputMatrix * 255)``.

    PlantVG.m accumulates overlapping cells by *addition*, so ``VoxelMatrix`` can
    hold values above 1; ``uint8(x*255)`` then saturates every one of them to
    255. Carrying a boolean volume and mapping True -> 255 is therefore
    bit-identical, and avoids the intermediate float volume entirely.
    """
    return np.where(volume, np.uint8(255), np.uint8(0))


def write_tiff(volume: np.ndarray, path) -> None:
    """Port of the ``imwrite(..., 'WriteMode', 'append')`` loop.

    Writes a single multi-page TIFF, one page per slice, readable by ImageJ.
    """

    __import__("tifffile").imwrite(str(path), to_uint8(volume), photometric="minisblack")

