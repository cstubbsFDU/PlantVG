def prepare_images(
    transverse_path,
    longitudinal_path,
    invert_transverse: bool = False,
    invert_longitudinal: bool = False,
) -> PreparedImages:
    """Sections 1-2: load, binarize, optionally invert, fill holes, trace.

    ``invert_*`` replaces PlantVG.m's ``while ~isCorrect`` confirmation loops.
    In a notebook the user inspects the overlay and re-runs the cell with the
    flag flipped, which is the same decision without the blocking prompt.
    """
    _, bw_t = read_binary_image(transverse_path)
    _, bw_l = read_binary_image(longitudinal_path)

    if invert_transverse:
        bw_t = ~bw_t
    if invert_longitudinal:
        bw_l = ~bw_l

    filled_t = imfill_holes(bw_t)
    filled_l = imfill_holes(bw_l)

    return PreparedImages(
        transverse=filled_t,
        longitudinal=filled_l,
        boundaries=bwboundaries(filled_t),
        boundaries_long=bwboundaries(filled_l),
    )


def analyze_lengths(
    prepared: PreparedImages,
    lower: float | None = None,
    upper: float | None = None,
    length_factor: float = 1.0,
    distribution: str = "Normal",
) -> LengthModel:
    """Sections 3-4: cell heights, outlier filter, distribution fit."""
    raw, counted = cell_heights(prepared.boundaries_long, prepared.longitudinal.shape[0])
    if raw.size == 0:
        raise ValueError(
            f"None of the {len(prepared.boundaries_long)} cells in your longitudinal "
            "image can be measured, because every one of them runs off the top or "
            "bottom edge. A cell that is cut off by the edge has an unknown true "
            "length, so it cannot be used.\n\n"
            "Try a longitudinal image that shows whole cells with some blank space "
            "above and below them, or zoom out so more complete cells are visible."
        )

    heights, avg, std = filter_heights(raw, lower, upper, length_factor)
    fitted = fit_distribution(heights, distribution)
    return LengthModel(raw, counted, heights, avg, std, fitted)


def generate_models(
    prepared: PreparedImages,
    lengths: LengthModel,
    params: Parameters,
    output_dir=".",
    progress=None,
) -> list[Path]:
    """Sections 5-7, looped over ``params.n_models``.

    Each model redraws both the end-cap positions and the per-cell wall
    thickness variation, so a single pair of input slides yields as many
    statistically distinct models as asked for -- the bootstrapping the
    manuscript describes.

    Parameters
    ----------
    progress
        Optional ``callable(model_index, n_models, stage)`` for UI feedback.
    """
    problems = params.validate()
    if problems:
        raise ValueError("invalid parameters: " + "; ".join(problems))

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    rng = np.random.default_rng(params.seed)
    written: list[Path] = []

    for quant in range(1, params.n_models + 1):
        if progress:
            progress(quant, params.n_models, "end caps")
        caps = generate_end_caps(
            prepared.n_cells, params.working_depth, lengths.fitted, lengths.avg, rng
        )

        if progress:
            progress(quant, params.n_models, "voxel matrix")
        volume = build_voxel_matrix(
            prepared.boundaries, caps, prepared.shape, params.working_depth,
            params.wall_thickness, params.wall_variation, params.radius, rng,
        )

        if progress:
            progress(quant, params.n_models, "writing tiff")
        out = crop_and_downsample(
            volume, params.slice_buffer, params.buffer_depth, params.dsf
        )
        path = output_dir / f"{params.output_name}-{quant}.tiff"
        write_tiff(out, path)
        written.append(path)

    return written
