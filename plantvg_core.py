def poly2mask(
    rows: np.ndarray,
    cols: np.ndarray,
    shape: tuple[int, int],
    x_rule: str = "left",
) -> np.ndarray:
    """MATLAB-compatible ``poly2mask``.

    Parameters
    ----------
    rows, cols
        Polygon vertices, 0-based, in the (row, col) order ``bwboundaries``
        returns. The polygon is closed automatically if it isn't already.
    shape
        ``(H, W)`` of the output mask.
    x_rule
        Which side of a span boundary is inclusive when a pixel centre falls
        exactly on it. ``"left"`` -> ``a <= px < b``; ``"right"`` -> ``a < px <= b``.
        These produce equal pixel *counts* but different pixel *sets*.

    Notes
    -----
    Vectorized over scanlines: all edges are tested against all rows at once,
    which is roughly 100x faster than the per-row Python loop and matters
    because Section 6 rasterizes one polygon per cell.
    """
    H, W = shape
    r = np.asarray(rows, dtype=np.float64)
    c = np.asarray(cols, dtype=np.float64)

    if r[0] != r[-1] or c[0] != c[-1]:
        r = np.append(r, r[0])
        c = np.append(c, c[0])

    r0, r1 = r[:-1], r[1:]
    c0, c1 = c[:-1], c[1:]

    horizontal = r0 == r1
    r0, r1, c0, c1 = r0[~horizontal], r1[~horizontal], c0[~horizontal], c1[~horizontal]
    if r0.size == 0:
        return np.zeros((H, W), bool)

    lo = np.minimum(r0, r1)
    hi = np.maximum(r0, r1)

    y = np.arange(H, dtype=np.float64)[:, None]          # (H, 1)
    # MATLAB's rule: lower endpoint exclusive, upper endpoint inclusive.
    hits = (lo[None, :] < y) & (y <= hi[None, :])        # (H, E)

    with np.errstate(divide="ignore", invalid="ignore"):
        xs = c0[None, :] + (y - r0[None, :]) * ((c1 - c0) / (r1 - r0))[None, :]

    xs = np.where(hits, xs, np.inf)
    xs.sort(axis=1)

    px = np.arange(W, dtype=np.float64)[None, :]         # (1, W)
    mask = np.zeros((H, W), bool)

    n_cross = hits.sum(axis=1)
    for k in range(0, int(n_cross.max()), 2):
        a = xs[:, k][:, None]
        b = xs[:, k + 1][:, None] if k + 1 < xs.shape[1] else np.full_like(a, np.inf)
        valid = np.isfinite(a) & np.isfinite(b)
        if x_rule == "left":
            span = (px >= a) & (px < b)
        else:
            span = (px > a) & (px <= b)
        mask |= span & valid

    return mask


