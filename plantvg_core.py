# ---------------------------------------------------------------------------
# Section 5 -- end cap locations
# ---------------------------------------------------------------------------

def generate_end_caps(
    n_cells: int,
    voxel_depth: int,
    fitted: FittedDistribution,
    avg: float,
    rng: np.random.Generator,
) -> np.ndarray:
    """Port of the ``endCapArray`` construction.

    Each cell gets an independent random walk up the voxel column: start at a
    uniform random offset within one mean cell length, mark an end cap, then
    step by a draw from the fitted distribution until past the top.

    Returns
    -------
    ndarray of bool, shape ``(n_cells, voxel_depth)``
        Column ``k`` corresponds to MATLAB's 1-based slice ``k+1``.
    """
    caps = np.zeros((n_cells, voxel_depth), dtype=bool)

    for i in range(n_cells):
        # MATLAB: current_pos = round(rand() * Avg), 1-based slice index.
        pos = int(matlab_round(rng.random() * avg))

        while pos <= voxel_depth:
            # MATLAB guards `current_pos >= 1` because round(rand()*Avg) can be 0.
            if pos >= 1:
                caps[i, pos - 1] = True
            pos += fitted.step_size(rng)

    return caps


# ---------------------------------------------------------------------------
# Section 6 -- fillet profiles
# ---------------------------------------------------------------------------

def fillet_arrays(
    end_cap_vector: np.ndarray,
    radius: int,
    cell_wall_thickness: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Port of the ``subInner`` / ``subOuter`` / ``fillArray`` construction.

    These three arrays say, for each slice, how deeply to erode the inner mask,
    how deeply to erode the outer mask, and whether the cell is solid there
    (i.e. inside an end cap, so the lumen is not punched out).

    The quarter-sine profiles give the end-cap fillet its curvature. Written
    with MATLAB's 1-based slice index ``k`` throughout to keep the index
    arithmetic legible against the original.

    Note that the bounds test guards *both* the lower and upper write index with
    a single condition, so when one side falls outside the volume neither side
    is written. That asymmetry is MATLAB's and is preserved deliberately.
    """
    depth = len(end_cap_vector)
    sub_inner = np.zeros(depth, dtype=np.float64)
    sub_outer = np.zeros(depth, dtype=np.float64)
    fill_array = np.zeros(depth, dtype=bool)

    thk = int(matlab_round(cell_wall_thickness / 2))
    ri = int(radius)
    ro = ri + thk

    for k in range(1, depth + 1):
        if not end_cap_vector[k - 1]:
            continue

        # --- inner mask erosion profile
        for j in range(1, ri + 1):
            if (k - thk - ri + j) > 0 and (k + thk + ri - j) < depth + 1:
                value = np.sin(j * np.pi / 2 / ri) * ri
                sub_inner[(k - thk - ri + j) - 1] = value
                sub_inner[(k + thk + ri - j) - 1] = value

        if (k - thk) > 0 and (k + thk) < depth + 1:
            sub_inner[(k - thk) - 1 : (k + thk)] = ri

        # --- outer mask erosion profile
        for j in range(1, ri + thk + 1):
            if (k - thk - ri + j) > 0 and (k + thk + ri - j) < depth + 1:
                value = np.sin(j * np.pi / 2 / (ri + cell_wall_thickness)) * (ri + thk)
                sub_outer[(k - ro + j) - 1] = value
                sub_outer[(k + ro - j) - 1] = value

        # --- solid (end cap) region
        if (k - thk) > 0 and (k + thk) < depth + 1:
            fill_array[(k - thk) - 1 : (k + thk)] = True

    return sub_inner, sub_outer, fill_array


