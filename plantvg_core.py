def graythresh(img: np.ndarray, num_bins: int = 256) -> float:
    """Otsu threshold, reimplemented to match MATLAB's ``graythresh`` exactly.

    MATLAB differs from ``skimage.filters.threshold_otsu`` in two ways that
    matter at the boundary of a tie:

    1. It always uses a 256-bin histogram over the *class range* of the image
       (0..255 for uint8), not over ``[img.min(), img.max()]``.
    2. On ties it takes the **mean** of all maximizing bin indices, which can
       land the threshold halfway between two bins.

    Returns
    -------
    float
        Normalized threshold in ``[0, 1]``, as MATLAB does.
    """
    img = np.asarray(img)
    if img.dtype != np.uint8:
        raise TypeError(f"graythresh expects uint8, got {img.dtype}")

    counts = np.bincount(img.ravel(), minlength=num_bins).astype(np.float64)
    total = counts.sum()
    if total == 0:
        return 0.0

    p = counts / total
    omega = np.cumsum(p)
    # MATLAB uses 1-based bin centres (1..num_bins) here.
    mu = np.cumsum(p * np.arange(1, num_bins + 1, dtype=np.float64))
    mu_t = mu[-1]

    # Suppress the 0/0 at omega == 0 and omega == 1; MATLAB produces NaN there
    # and max() ignores NaN.
    with np.errstate(divide="ignore", invalid="ignore"):
        sigma_b_squared = (mu_t * omega - mu) ** 2 / (omega * (1.0 - omega))

    if np.all(np.isnan(sigma_b_squared)):
        return 0.0

    maxval = np.nanmax(sigma_b_squared)
    # MATLAB: idx = mean(find(sigma_b_squared == maxval)), 1-based.
    idx = np.mean(np.flatnonzero(sigma_b_squared == maxval)) + 1.0
    return (idx - 1.0) / (num_bins - 1.0)


def imbinarize(img: np.ndarray) -> np.ndarray:
    """Global Otsu binarization matching MATLAB ``imbinarize(I)`` for uint8.

    MATLAB computes ``BW = im2double(I) > graythresh(I)``, i.e. a *strict*
    greater-than against the normalized level.
    """
    img = np.asarray(img)
    level = graythresh(img)
    return (img.astype(np.float64) / 255.0) > level


def read_binary_image(path) -> tuple[np.ndarray, np.ndarray]:
    """Port of ``I = imread(p); BW = imbinarize(I(:,:,1))``.

    MATLAB takes the **first channel only** -- the red channel for an RGB or
    RGBA image, not a luminance conversion. Reproduced exactly here.

    Returns
    -------
    (raw, bw)
        ``raw`` is the image as read; ``bw`` is the boolean binarization of its
        first channel.
    """

    raw = np.array(__import__("PIL.Image", fromlist=["Image"]).open(path))
    channel = raw[:, :, 0] if raw.ndim == 3 else raw
    if channel.dtype != np.uint8:
        raise TypeError(f"expected uint8 image data, got {channel.dtype}")
    return raw, imbinarize(channel)


