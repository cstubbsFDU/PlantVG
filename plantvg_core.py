@dataclass
class FittedDistribution:
    """A fitted cell-length distribution and its sampler.

    Attributes
    ----------
    name
        Display name, one of :data:`DISTRIBUTIONS`.
    params
        Parameters in **MATLAB's** order, matching ``pd.Params`` in PlantVG.m, so
        that anything printed or logged lines up with the original tool.
    sample
        ``sample(rng) -> float``, one draw in MATLAB's parameterization.
    """

    name: str
    params: tuple[float, ...]
    sample: Callable[[np.random.Generator], float]

    def step_size(self, rng: np.random.Generator) -> int:
        """One end-cap step: a draw, MATLAB-rounded, floored at 1.

        The floor reproduces PlantVG.m's guard against a zero or negative step
        sending the ``while current_pos <= voxelDepth`` loop into an infinite
        spin.
        """
        return max(1, int(matlab_round(self.sample(rng))))


DISTRIBUTIONS = ("Normal", "Exponential", "Gamma", "Poisson", "Weibull")


def fit_distribution(height: np.ndarray, name: str) -> FittedDistribution:
    """Port of ``pd = fitdist(height', name); params = pd.Params``.

    Parameters
    ----------
    height
        Filtered, length-factor-scaled cell heights.
    name
        One of :data:`DISTRIBUTIONS` (case-insensitive).
    """
    x = np.asarray(height, dtype=np.float64).ravel()
    if x.size == 0:
        raise ValueError("cannot fit a distribution to an empty height vector")

    key = name.strip().lower()

    if key == "normal":
        # MATLAB normfit: mu = sample mean, sigma with the **N-1** denominator.
        # scipy.stats.norm.fit would return the MLE (N denominator) instead.
        mu = float(np.mean(x))
        sigma = float(np.std(x, ddof=1)) if x.size > 1 else 0.0
        return FittedDistribution(
            "Normal", (mu, sigma),
            lambda rng, mu=mu, sigma=sigma: rng.normal(mu, sigma),
        )

    if key == "exponential":
        # MATLAB expfit / exprnd are parameterized by the **mean** mu.
        # scipy calls the same quantity `scale`.
        mu = float(np.mean(x))
        return FittedDistribution(
            "Exponential", (mu,),
            lambda rng, mu=mu: rng.exponential(mu),
        )

    if key == "gamma":
        # MATLAB gamfit -> [a, b] = [shape, scale]; gamrnd(a, b) likewise.
        # scipy needs floc=0 to fit the same two-parameter family MATLAB fits.

        a, loc, b = stats.gamma.fit(x, floc=0)
        a, b = float(a), float(b)
        return FittedDistribution(
            "Gamma", (a, b),
            lambda rng, a=a, b=b: rng.gamma(a, b),
        )

    if key == "poisson":
        # MATLAB poissfit: lambda = sample mean. fitdist('Poisson') requires
        # non-negative integer data and errors otherwise -- worth surfacing
        # early, because a non-integer lengthFactor makes the heights fractional.
        if np.any(x < 0) or np.any(x != np.floor(x)):
            raise ValueError(
                "The Poisson distribution only works with whole-number cell "
                "lengths, but the cell length factor has made them fractional.\n\n"
                "Either set the cell length factor to a whole number (1, 2, 3...), "
                "or choose a different distribution -- Normal and Gamma both handle "
                "fractional lengths."
            )
        lam = float(np.mean(x))
        return FittedDistribution(
            "Poisson", (lam,),
            lambda rng, lam=lam: float(rng.poisson(lam)),
        )

    if key == "weibull":
        # THE SWAP. MATLAB wblfit -> [a, b] = [**scale**, **shape**], and
        # wblrnd(a, b) takes them in that order. scipy.stats.weibull_min is
        # (c=**shape**, loc, scale). Passing MATLAB's tuple straight into scipy
        # positionally silently fits/samples the wrong distribution.

        shape_c, loc, scale_a = stats.weibull_min.fit(x, floc=0)
        a, b = float(scale_a), float(shape_c)   # MATLAB order: (scale, shape)
        return FittedDistribution(
            "Weibull", (a, b),
            lambda rng, a=a, b=b: a * rng.weibull(b),
        )

    raise ValueError(
        f"unknown distribution {name!r}; expected one of {DISTRIBUTIONS}"
    )

