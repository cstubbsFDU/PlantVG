def cell_heights(boundaries: list[np.ndarray], image_height: int) -> tuple[np.ndarray, np.ndarray]:
    """Port of the cell-length extraction loop.

    A cell is counted only if its trace is fully interior in the row direction,
    so cells clipped by the top or bottom image edge don't skew the
    distribution. MATLAB's test is ``max(rows) < H && min(rows) > 1`` in 1-based
    indexing; translated to 0-based that is ``max < H-1 && min > 0``.

    Returns
    -------
    (heights, counted)
        ``heights`` is the height of each *accepted* cell, in source order.
        ``counted`` is a boolean mask over ``boundaries`` marking which were
        accepted -- needed to reproduce MATLAB's overlay plot.
    """
    heights: list[float] = []
    counted = np.zeros(len(boundaries), dtype=bool)

    for i, b in enumerate(boundaries):
        rmin, rmax = b[:, 0].min(), b[:, 0].max()
        if rmax < image_height - 1 and rmin > 0:
            heights.append(rmax - rmin)
            counted[i] = True

    return np.asarray(heights, dtype=np.float64), counted


def filter_heights(
    heights: np.ndarray,
    lower: float | None = None,
    upper: float | None = None,
    length_factor: float = 1.0,
) -> tuple[np.ndarray, float, float]:
    """Apply the cell-length factor and the user's outlier cut.

    This replaces the ``hist`` + ``ginput(2)`` interaction. ``lower``/``upper``
    are the two values the user would have clicked on the histogram; ``None``
    means no cut on that side.

    Order of operations
    -------------------
    ``length_factor`` is applied **once, up front**, so that the histogram, the
    user's thresholds, and the returned heights are all in the same units.

    This corrects a bug in PlantVG.m, which plotted ``lengthFactor*heightPre``
    but compared the *unscaled* ``heightPre`` against the clicked thresholds,
    then applied ``lengthFactor`` a second time to the survivors. The effect was
    invisible at the default ``lengthFactor = 1.0`` and wrong everywhere else:
    at ``lengthFactor = 2``, clicking a cut at 100 on the histogram actually cut
    at 50, and the surviving cells were then doubled again.

    Returns
    -------
    (height, avg, std)
        ``std`` uses MATLAB's N-1 normalization (``ddof=1``), not numpy's default.
    """
    scaled = length_factor * np.asarray(heights, dtype=np.float64)

    keep = np.ones(scaled.shape, bool)
    if lower is not None:
        keep &= scaled > lower
    if upper is not None:
        keep &= scaled < upper

    height = scaled[keep]
    if height.size == 0:
        lo_txt = "-inf" if lower is None else f"{lower:.1f}"
        hi_txt = "+inf" if upper is None else f"{upper:.1f}"
        raise ValueError(
            f"The cell length range you chose ({lo_txt} to {hi_txt} pixels) excludes "
            f"every cell. The measured lengths run from {scaled.min():.1f} to "
            f"{scaled.max():.1f} pixels -- widen the slider to cover some of that range."
        )

    avg = float(np.mean(height))
    std = float(np.std(height, ddof=1)) if height.size > 1 else 0.0
    return height, avg, std

