@dataclass
class Parameters:
    """The eight fields of PlantVG.m's ``inputdlg``, plus the two selections
    that were separate dialogs, plus a seed.

    ``voxel_depth`` is the depth the *user* asks for. The working depth adds a
    buffer of ``2*radius + wall_thickness`` slices, which are cropped off at
    export because the end-cap random walk hasn't settled there yet.
    """

    voxel_depth: int = 100
    wall_thickness: int = 4
    wall_variation: int = 0
    radius: int = 2
    length_factor: float = 1.0
    output_name: str = "Output Voxel Mesh"
    dsf: int = 1
    n_models: int = 1
    distribution: str = "Normal"
    seed: int | None = None

    # Derived, matching PlantVG.m's arithmetic.
    @property
    def buffer_depth(self) -> int:
        return int(np.ceil(2 * self.radius + self.wall_thickness))

    @property
    def working_depth(self) -> int:
        return int(np.ceil(self.voxel_depth)) + self.buffer_depth

    @property
    def slice_buffer(self) -> int:
        return int(np.ceil(self.radius + self.wall_thickness))

    def output_shape(self, image_shape: tuple[int, int]) -> tuple[int, int, int]:
        """Predict the exported volume shape without generating it."""
        H, W = image_shape
        n = lambda a, b: len(range(a - 1, b, self.dsf))
        return (
            n(self.buffer_depth, self.working_depth),
            n(self.slice_buffer, H - self.slice_buffer),
            n(self.slice_buffer, W - self.slice_buffer),
        )

    def validate(self) -> list[str]:
        """Return a list of problems, empty if the parameters are usable."""
        problems = []
        if self.wall_thickness < 1:
            problems.append("wall thickness must be at least 1 pixel")
        if self.radius < 1:
            problems.append("end cap radius must be at least 1 pixel")
        if self.dsf < 1:
            problems.append("downsample factor must be at least 1")
        if self.n_models < 1:
            problems.append("number of models must be at least 1")
        if self.wall_variation < 0:
            problems.append("wall variation cannot be negative")
        if self.distribution not in DISTRIBUTIONS:
            problems.append(f"distribution must be one of {DISTRIBUTIONS}")
        return problems


@dataclass
class PreparedImages:
    """Traced transverse and longitudinal inputs."""

    transverse: np.ndarray
    longitudinal: np.ndarray
    boundaries: list[np.ndarray]
    boundaries_long: list[np.ndarray]

    @property
    def shape(self) -> tuple[int, int]:
        return self.transverse.shape

    @property
    def n_cells(self) -> int:
        return len(self.boundaries)


@dataclass
class LengthModel:
    """Fitted cell-length distribution plus the data behind it."""

    raw_heights: np.ndarray
    counted: np.ndarray
    heights: np.ndarray
    avg: float
    std: float
    fitted: FittedDistribution = field(repr=False)


