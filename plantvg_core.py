# ---------------------------------------------------------------------------
# MATLAB-compatible rounding
# ---------------------------------------------------------------------------

def matlab_round(x):
    """Round half **away from zero**, as MATLAB's ``round`` does.

    ``numpy.round`` uses banker's rounding (half to *even*): ``np.round(2.5)``
    is 2, whereas MATLAB's ``round(2.5)`` is 3. Every ``round(...rnd(...))`` call
    in PlantVG.m draws from a continuous distribution, so exact halves are rare
    -- but ``round(rand()*Avg)`` and the fillet arithmetic hit them often enough
    to matter, and the bias is systematic rather than random.
    """
    x = np.asarray(x, dtype=np.float64)
    return np.trunc(x + np.copysign(0.5, x))


