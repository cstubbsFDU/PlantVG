def cityblock_erosion_depth(mask: np.ndarray) -> np.ndarray:
    """Number of ``bwperim`` peels each pixel survives.

    ``peel(mask, n)`` -- the MATLAB loop -- equals ``cityblock_erosion_depth(mask) > n``.
    Outside-the-array counts as foreground, matching ``bwperim``'s in-image-only
    neighbour test, so pixels on the image border never erode.
    """
    return ndi.distance_transform_cdt(mask, metric="taxicab")


def _disk_dilate(points_rc: np.ndarray, shape: tuple[int, int], radius: float) -> np.ndarray:
    """Union of Euclidean disks of ``radius`` centred on each ``(row, col)`` point.

    Equivalent to PlantVG.m's per-boundary-pixel ``sqrt(...) <= cellWallThickness``
    accumulation, but computed as a single distance transform.

    PlantVG.m *sums* the disks, so overlaps hold values above 1. That is
    immaterial: every downstream consumer (``imfill``, ``bwperim``, and the final
    ``uint8(x*255)`` which saturates at 255) treats any nonzero value
    identically, so the boolean union produces a bit-identical TIFF.
    """
    seeds = np.ones(shape, dtype=bool)
    seeds[points_rc[:, 0].astype(int), points_rc[:, 1].astype(int)] = False
    return ndi.distance_transform_edt(seeds) <= radius


